x = 10
y = 20

# Sprawdzanie relacji między liczbami
czy_wieksze = x > y        # Wynik: False
czy_rowne = x == 10        # Wynik: True
czy_rozne = x != y         # Wynik: True

print(f"Czy x jest większe od y? {czy_wieksze}")
print(f"Czy x wynosi 10? {czy_rowne}")
print(f"Czy x jest różne od y? {czy_rozne}")