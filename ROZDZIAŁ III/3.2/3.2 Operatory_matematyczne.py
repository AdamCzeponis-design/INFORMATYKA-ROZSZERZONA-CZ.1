# Operacje arytmetyczne
a = 15
b = 4

print(f"Suma: {a + b}")
print(f"Różnica: {a - b}")
print(f"Iloczyn (mnożenie): {a * b}")
print(f"Dzielenie: {a / b}")
print(f"Dzielenie całkowite: {a // b}")
print(f"Reszta z dzielenia (modulo): {a % b}")
print(f"Potęgowanie (a do potęgi b): {a ** 2}")